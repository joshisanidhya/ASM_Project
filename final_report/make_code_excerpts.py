"""Write final_report/code_appendix.tex and final_report/code/*.py: short excerpts of the repository's own source.

Every line is a line of the source function (obtained with inspect.getsource); docstrings are dropped and omitted
stretches are marked with '...'. Run from the project root:  python final_report/make_code_excerpts.py
"""
import ast
import inspect
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from headway import distributions, mcmc, stochastic_process, validation  # noqa: E402

OUT = ROOT / "final_report"
TRANSLIT = {"\u2014": "-", "\u2013": "-", "\u2265": ">=", "\u2264": "<=", "\u00d7": "x", "\u2192": "->", "\u2248": "~",
            "\u00b1": "+/-", "\u03b1": "alpha", "\u03b2": "beta", "\u03b3": "gamma", "\u03bb": "lambda", "\u03bc": "mu",
            "\u03c3": "sigma", "\u03b8": "theta", "\u00b2": "^2"}


def source(obj):
    import textwrap
    return textwrap.dedent(inspect.getsource(obj)).rstrip("\n").split("\n")


def drop_docstring(lines):
    tree = ast.parse("\n".join(lines))
    fn = tree.body[0]
    d = fn.body[0]
    if isinstance(d, ast.Expr) and isinstance(getattr(d, "value", None), ast.Constant) and isinstance(d.value.value, str):
        return lines[:d.lineno - 1] + lines[d.end_lineno:]
    return lines


def between(lines, start, stop=None):
    i = next(k for k, s in enumerate(lines) if s.strip().startswith(start))
    j = len(lines) if stop is None else next(k for k, s in enumerate(lines) if k > i and s.strip().startswith(stop))
    return lines[i:j]


def drop_comments(lines):
    return [s for s in lines if not s.strip().startswith("#")]


def metropolis_excerpt():
    s = source(mcmc.metropolis)
    sig_end = next(k for k, t in enumerate(s) if t.startswith(") ->"))
    return (s[:sig_end + 1] + ["    ..."] + [l for l in between(s, "x = np.array(x0", "# If initial logp") if l.strip()] + ["    ..."]
            + between(s, "# Initial proposal covariance", "n_post = max(1") + ["    ..."])


def _trim_covariance(lines):
    """Drop the covariance re-estimation block (the text describes it) and mark the omission."""
    i = next(k for k, t in enumerate(lines) if "Re-estimate proposal covariance" in t)
    j = next(k for k, t in enumerate(lines) if k > i and t.strip() == "pass")
    return lines[:i] + ["            ..."] + lines[j + 1:]


EXCERPTS = [
    ("proposed_distribution",
     "Proposed headway distribution: normalised density and closed-form distribution function, Eqs.~\\eqref{eq:density}--\\eqref{eq:norm} "
     "(\\texttt{headway/distributions.py}; docstrings omitted).", "lst:dist",
     drop_docstring(source(distributions._proposed_pdf)) + [""] + drop_docstring(source(distributions._proposed_cdf))),
    ("metropolis_sampler",
     "Adaptive random-walk Metropolis--Hastings sampler: proposal, acceptance rule of Eq.~\\eqref{eq:accept} and warmup-only adaptation "
     "(\\texttt{headway/mcmc.py}; initialisation, covariance re-estimation and output handling omitted).", "lst:mh",
     _trim_covariance(metropolis_excerpt())),
    ("renewal_simulation",
     "Simulation of the renewal counting process $N(t)$ from i.i.d.\\ resampled headways (\\texttt{headway/validation.py}).",
     "lst:renewal", drop_docstring(source(validation.simulate_counts))),
    ("markov_estimation",
     "Estimation of the regime transition matrix from within-run pairs of consecutive samples only "
     "(\\texttt{headway/stochastic\\_process.py}).", "lst:markov",
     drop_docstring(source(stochastic_process.TrafficRegimeMarkovChain.from_headways.__func__))),
]


def ascii_(text):
    for k, v in TRANSLIT.items():
        text = text.replace(k, v)
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()


def main():
    (OUT / "code").mkdir(parents=True, exist_ok=True)
    tex = ["% Generated by final_report/make_code_excerpts.py from the repository source.",
           "\\section{Code Excerpts}\\label{app:code}", ""]
    for stem, caption, label, lines in EXCERPTS:
        text = ascii_("\n".join(lines)) + "\n"
        (OUT / "code" / f"{stem}.py").write_text(text, encoding="ascii", newline="\n")
        tex += [f"\\lstinputlisting[caption={{{caption}}},label={{{label}}}]{{code/{stem}.py}}", ""]
        print(stem, len(lines), "lines")
    (OUT / "code_appendix.tex").write_text("\n".join(tex), encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
