"""Write report/code_appendix.tex and report/code/*.py from the repository's own source.

    uv run python -m headway.make_code_appendix [--out report]

Every listing is the exact source of a function in this repository (inspect.getsource), so the
appendix cannot drift from the implementation. Only non-ASCII punctuation in comments is
transliterated, because pdflatex cannot read it inside listings.
"""
import argparse
import inspect
import unicodedata
from pathlib import Path

from . import detector, distributions, fit, mcmc, stochastic_process, validation
from .datasets import common

TRANSLIT = {"\u2014": "-", "\u2013": "-", "\u2265": ">=", "\u2264": "<=", "\u00d7": "x", "\u2192": "->",
            "\u2248": "~", "\u00b1": "+/-", "\u03b1": "alpha", "\u03b2": "beta", "\u03b3": "gamma",
            "\u03bb": "lambda", "\u03bc": "mu", "\u03c3": "sigma", "\u03b8": "theta", "\u00b2": "^2"}

# (file stem, caption, label, source object)
LISTINGS = [
    ("proposed_pdf", "Density of the proposed headway distribution, normalised on $[\\alpha,\\infty)$ (\\texttt{distributions.py}).",
     "lst:pdf", distributions._proposed_pdf),
    ("proposed_cdf", "Distribution function of the proposed distribution, Eq.~\\eqref{eq:cdf} (\\texttt{distributions.py}).",
     "lst:cdf", distributions._proposed_cdf),
    ("make_logpost", "Binned log-posterior used by the sampler; \\texttt{likelihood} selects the paper's or the truncated likelihood (\\texttt{fit.py}).",
     "lst:logpost", fit.make_logpost),
    ("metropolis", "Adaptive random-walk Metropolis--Hastings sampler (\\texttt{mcmc.py}).", "lst:mh", mcmc.metropolis),
    ("chain", "One MCMC chain, including the log-gap coordinates for the shifted exponential (\\texttt{fit.py}).",
     "lst:chain", fit._chain),
    ("segment_ids", "Trajectory runs: consecutive seconds of one vehicle (\\texttt{datasets/common.py}).", "lst:segments",
     common.segment_ids),
    ("from_headways", "Markov transition estimation from within-run pairs only (\\texttt{stochastic\\_process.py}).",
     "lst:markov", stochastic_process.TrafficRegimeMarkovChain.from_headways.__func__),
    ("simulate_counts", "Simulation of the renewal counting process $N(t)$ (\\texttt{validation.py}).", "lst:renewal",
     validation.simulate_counts),
    ("renewal_validation", "Simulated moments of $N(t)$ against renewal theory (\\texttt{validation.py}).", "lst:rv",
     validation.renewal_validation),
    ("markov_validation", "Chapman--Kolmogorov, stationarity and first- against second-order checks (\\texttt{validation.py}).",
     "lst:mv", validation.markov_validation),
    ("crossing_times", "Virtual-detector crossing times by linear interpolation, Eq.~\\eqref{eq:crossing} (\\texttt{detector.py}).",
     "lst:crossing", detector.crossing_times),
    ("window_count_summary", "Count dispersion in fixed windows against renewal and Poisson theory (\\texttt{detector.py}).",
     "lst:window", detector.window_count_summary),
]


def ascii_source(obj) -> str:
    src = inspect.getsource(obj).rstrip() + "\n"
    for k, v in TRANSLIT.items():
        src = src.replace(k, v)
    return unicodedata.normalize("NFKD", src).encode("ascii", "ignore").decode()


def build(out="report"):
    out = Path(out)
    (out / "code").mkdir(parents=True, exist_ok=True)
    tex = ["% Generated by `python -m headway.make_code_appendix`: exact source of the functions named in each caption.",
           "\\section{Source Code}\\label{app:code}",
           "The listings below are the exact source of the functions in the project repository "
           "(\\texttt{headway/} package); they are extracted automatically, not retyped.", ""]
    # newline="\n": a stray carriage return (Windows) is read by TeX as a character
    for stem, caption, label, obj in LISTINGS:
        (out / "code" / f"{stem}.py").write_text(ascii_source(obj), encoding="ascii", newline="\n")
        tex += [f"\\lstinputlisting[caption={{{caption}}},label={{{label}}}]{{code/{stem}.py}}", ""]
    (out / "code_appendix.tex").write_text("\n".join(tex), encoding="ascii", newline="\n")
    print(f"wrote {out / 'code_appendix.tex'} and {len(LISTINGS)} files in {out / 'code'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="report")
    build(ap.parse_args().out)
